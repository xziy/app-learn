}

/** 1 фразе, 2 фразах, 5 фразах: «встречается в» takes the prepositional case, which has one form for 1 and another. */
private fun russianPhrases(count: Int): String = if (count % 10 == 1 && count % 100 != 11) "фразе" else "фразах"
