    val title: String,
    /** What the way to the dictionary says in the list, with the number of words seen. */
    val entry: String,
    val search: String,
    val seen: String,
    val unknown: String,
    val known: String,
    val all: String,
    /** `Встречено 214 · знаю 120`. */
    val summary: (seen: Int, known: Int) -> String,
    val none: String,
    val noneFound: String,
    val noDictionary: String,
    val know: String,
    val doNotKnow: String,
    val forgetSeen: String,
    val forgetSeenSure: String,
    val say: String,
    val plural: String,
    val uncountable: String,
    val both: String,
    val pluralOnly: String,
    val same: String,
    val collective: String,
    val inPhrase: String,
    val synonyms: String,
    val antonyms: String,
    val collocations: String,
    val family: String,
    val kinds: Map<String, String>,
    val notes: String,
    val notFilled: String,
    /** `Встречается в 31 фразе`. */
    val uses: (Int) -> String,
    val loading: String,
) {
    companion object {
        val Ru = WordStrings(
