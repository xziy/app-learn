/**
 * The host on Superizer (.ai-notes): a host and nothing else, with a package, a scheme, settings and
 * a window of its own. The apps live in apps/<name>. The desktop and the iPhone: a multiplatform
 * module, so Android and the web come back as targets rather than as a rewrite.
 */
plugins {
    alias(libs.plugins.kotlinMultiplatform)
    alias(libs.plugins.composeMultiplatform)
    alias(libs.plugins.composeCompiler)
    alias(libs.plugins.kotlinxSerialization)
}

val appVersionName = "0.1"

/** A checkout without `.git`, or without a commit yet, builds with "unknown". */
val gitDir = layout.projectDirectory.dir("../.git").asFile

fun git(vararg args: String): String? = if (!gitDir.exists()) null else runCatching {
    val result = providers.exec {
        commandLine("git", *args)
        workingDir = rootDir
        // A repository with no commit yet fails `rev-parse HEAD`; that is "unknown", not a
        // configuration-cache problem.
        isIgnoreExitValue = true
    }
    if (result.result.get().exitValue != 0) null else result.standardOutput.asText.get().trim().ifEmpty { null }
}.getOrNull()

/** BuildInfo.kt for commonMain, so the drawer shows which build it is. */
val generateBuildInfo by tasks.registering {
    val outputDir = layout.buildDirectory.dir("generated/buildinfo/kotlin")
    val commit = git("rev-parse", "--short", "HEAD") ?: "unknown"
    val dirty = git("status", "--porcelain")?.isNotEmpty() == true
    val version = appVersionName

    inputs.property("commit", commit)
    inputs.property("dirty", dirty)
    inputs.property("version", version)
    outputs.dir(outputDir)

    doLast {
        val dir = outputDir.get().asFile.resolve("cx/m42/english")
        dir.mkdirs()
        dir.resolve("BuildInfo.kt").writeText(
            """
            package cx.m42.english

            /** Generated by the :composeApp:generateBuildInfo Gradle task. Do not edit. */
            object BuildInfo {
                const val VERSION: String = "$version"
                const val COMMIT: String = "$commit"
                const val DIRTY: Boolean = $dirty
            }

            """.trimIndent(),
        )
    }
}

kotlin {
    jvm("desktop")

    /**
     * The iPhone app: a static framework that `iosApp/` links. Only the klibs build without Xcode;
     * linking this framework takes a Mac with it (README, «iPhone»).
